package net.pamytno.deck.integration.ai;

/**
 * Общие для всех AI-провайдеров правила оформления вопросов и карточек. Фронт показывает простую разметку:
 * абзацы, списки «- », варианты ответа «A. …», код в ``` и выделение **жирным**.
 */
public final class AiFormatRules {

    /** Правило генерации вопросов: задача с вариантами ответа становится отдельным вопросом целиком. */
    public static final String QUESTIONS = """
            - Если во фрагменте есть задача с вариантами ответа, сделай по ней отдельный вопрос целиком: \
            условие кратко (2–4 предложения с ключевыми цифрами), затем с новой строки сам вопрос, выделенный \
            **жирным**, затем варианты — каждый с новой строки в виде «A. …». Остальные вопросы — по разбору решения.
            """;

    /** Правила оформления сторон карточки. */
    public static final String CARD = """
            - Разметка: абзацы разделяй пустой строкой, выделение — **жирным**, перечисления — списком, \
            каждый пункт с новой строки через «- », схему потока данных или код — в блоке ```. \
            Заголовки, таблицы и HTML не используй.
            - front: если у вопроса есть варианты ответа, сохрани условие, сам вопрос (**жирным**) и все варианты — \
            каждый с новой строки в виде «A. …».
            - back: ответ из одной фразы не выделяй. Более длинный начни с прямого ответа **жирным** \
            (для задачи с вариантами — буква и название верного варианта), затем коротко объясни почему. \
            Для задачи с вариантами добавь, почему не подходят остальные: списком, по пункту «- B — …» на вариант.
            """;

    /**
     * Запрещает создание экземпляров.
     */
    private AiFormatRules() {
    }
}

package net.pamytno.deck.integration.ai.anthropic;

/**
 * Промпты для Claude. Материал пользователя передаётся внутри XML-тегов и отделён от инструкций.
 */
final class AnthropicPrompts {

    /** Инструкция генерации вопросов; {@code %d} — максимум вопросов на фрагмент. */
    static final String QUESTIONS_SYSTEM = """
            Ты помогаешь студенту готовиться по его учебным материалам. По фрагменту материала составь \
            вопросы для самопроверки — потом они станут карточками для интервального повторения.

            Правила:
            - Вопросы опираются только на текст фрагмента; не добавляй фактов, которых в нём нет.
            - Каждый вопрос проверяет одну мысль: определение, причину, следствие, сравнение, шаг процесса.
            - Для списка слов или пар «слово — перевод» спрашивай перевод или значение слова.
            - sourceFragment — дословная цитата из фрагмента (1–3 предложения), на которой основан вопрос.
            - Пиши на языке материала.
            - Не больше %d вопросов. Если во фрагменте нет учебного содержания, верни пустой список.""";

    /** Инструкция составления карточки. */
    static final String CARD_SYSTEM = """
            Ты составляешь карточку для интервального повторения по вопросу и фрагменту учебного материала.

            Правила:
            - front — вопрос; можно уточнить формулировку, но не меняй смысл.
            - back — ответ только по материалу, без фактов извне. Если хватает одной фразы — одна фраза; \
            не длиннее 10 предложений.
            - Если в материале нет ответа, прямо напиши об этом в back.
            - Пиши на языке материала.""";

    /**
     * Запрещает создание экземпляров.
     */
    private AnthropicPrompts() {
    }

    /**
     * Сообщение с фрагментом для генерации вопросов.
     *
     * @param material фрагмент материала
     * @return текст сообщения пользователя
     */
    static String questionsMessage(String material) {
        return "<material>\n" + material + "\n</material>";
    }

    /**
     * Сообщение с вопросом и контекстом для карточки.
     *
     * @param question вопрос
     * @param context  фрагмент материала
     * @return текст сообщения пользователя
     */
    static String cardMessage(String question, String context) {
        return "<question>\n" + question + "\n</question>\n\n<material>\n" + context + "\n</material>";
    }
}

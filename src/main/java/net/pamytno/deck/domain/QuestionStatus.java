package net.pamytno.deck.domain;

/**
 * Состояние вопроса в отборе пользователем.
 */
public enum QuestionStatus {

    /** Предложен AI, пользователь ещё не решил. */
    GENERATED,
    /** Пользователь решил изучать вопрос. */
    APPROVED,
    /** Пользователь решил не изучать вопрос. */
    REJECTED,
    /** По вопросу создана карточка — статус окончательный. */
    CARD_CREATED
}

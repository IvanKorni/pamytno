package net.pamytno.topic.domain;

/**
 * Состояние темы, вычисляемое по состояниям её источников.
 */
public enum TopicStatus {

    /** Источников ещё нет. */
    DRAFT,
    /** Хотя бы один источник ещё обрабатывается. */
    PROCESSING,
    /** Обработка завершена, есть хотя бы один готовый источник. */
    READY,
    /** Обработка завершена, но ни один источник не удалось обработать. */
    ERROR
}
